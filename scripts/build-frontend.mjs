import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = resolve(projectRoot, "frontend");
const outputDirectory = resolve(projectRoot, "dist");
const configuredApiUrl = String(process.env.S3_GEAR_GENERATOR_API_URL || "").trim();

if (!configuredApiUrl) {
  throw new Error("S3_GEAR_GENERATOR_API_URL is required, for example https://s3-gear-generator-api.example.workers.dev");
}

let parsedApiUrl;
try {
  parsedApiUrl = new URL(configuredApiUrl);
} catch {
  throw new Error("S3_GEAR_GENERATOR_API_URL must be a valid http(s) URL");
}

if (!['http:', 'https:'].includes(parsedApiUrl.protocol) || parsedApiUrl.pathname !== "/" || parsedApiUrl.search || parsedApiUrl.hash) {
  throw new Error("S3_GEAR_GENERATOR_API_URL must be the Worker base URL without a path, query, or hash");
}

const apiBaseUrl = parsedApiUrl.origin;
const runtimeConfig = {
  apiBaseUrl,
  demoMode: false,
};

await rm(outputDirectory, { recursive: true, force: true });
await mkdir(outputDirectory, { recursive: true });
await cp(sourceDirectory, outputDirectory, { recursive: true });
await writeFile(
  resolve(outputDirectory, "config.js"),
  `// Generated at build time. Do not edit this file in dist.\nwindow.S3S_WEB_CONFIG = ${JSON.stringify(runtimeConfig, null, 2)};\n`,
  "utf8",
);

console.log(`Frontend built in ${outputDirectory}`);
console.log(`API base URL: ${apiBaseUrl}`);
